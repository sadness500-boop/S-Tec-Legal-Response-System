/* 국가법령정보센터 원문 주소 */
function lawUrl(x) {
  if (!x) return 'https://www.law.go.kr/';
  if (x.q) return 'https://www.law.go.kr/LSW/precSc.do?query=' + encodeURIComponent(x.q);
  if (/계약서|지침/.test(x.law)) return 'https://www.law.go.kr/main.html';
  const art = /^제\d+조(의\d+)?$/.test(x.art) ? '/' + x.art : '';
  if (x.law === '영사관계에 관한 비엔나협약') return 'https://www.law.go.kr/trtySc.do?query=' + encodeURIComponent('영사관계에 관한 비엔나협약');
  return 'https://www.law.go.kr/법령/' + x.law.replace(/\s+/g, '') + art;
}

